import { expect, test } from '@playwright/test'

test('스틸라 단어 CRUD, 예문 위치, 복습 이어가기', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/')
  await page.getByRole('navigation', { name: '내 앱' }).getByRole('link', { name: '스틸라' }).click()
  await expect(page).toHaveURL('/stilla')
  await expect(page.getByRole('heading', { name: '스틸라' })).toBeVisible()
  await page.getByRole('button', { name: '첫 단어 담기' }).click()
  const firstWord = page.getByRole('textbox', { name: '1행 단어' })
  const firstMeaning = page.getByRole('textbox', { name: '1행 뜻' })
  const secondWord = page.getByRole('textbox', { name: '2행 단어' })
  await firstWord.fill('again')
  await firstWord.press('Tab')
  await expect(firstMeaning).toBeFocused()
  await firstMeaning.fill('다시')
  await firstMeaning.press('Tab')
  await expect(secondWord).toBeFocused()
  await secondWord.press('Shift+Tab')
  await expect(firstMeaning).toBeFocused()

  await secondWord.evaluate(element => {
    const clipboardData = new DataTransfer()
    clipboardData.setData('text/plain', 'look\t보다\r\nAgain\t중복')
    element.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData }))
  })
  await expect(secondWord).toHaveValue('look')
  await expect(page.getByRole('textbox', { name: '2행 뜻' })).toHaveValue('보다')
  await expect(page.getByText('새 단어 2개 · 중복 1개')).toBeVisible()
  await page.getByRole('button', { name: '2개 담기' }).click()
  await page.getByText('예문 연결', { exact: true }).click()
  await page.getByLabel('문장', { exact: true }).fill('Again and again, say again.')
  await page.getByLabel('복습에서 가릴 표현 (선택)').fill('again')
  await page.getByLabel('가릴 위치').selectOption('1')
  await page.getByRole('button', { name: '예문 연결하기' }).click()
  await expect(page.getByRole('blockquote').getByText('Again and again, say again.')).toBeVisible()
  await page.getByRole('button', { name: '복습', exact: true }).click()
  await page.getByRole('button', { name: '3장 복습하기' }).click()
  await page.getByLabel('떠올린 답').fill('다시')
  await page.getByRole('button', { name: '답 보기' }).click()
  await expect(page.getByText('기록된 답과 같아요.')).toBeVisible()
  await page.getByRole('button', { name: '기억함' }).click()
  const cloze = page.getByRole('heading', { name: 'Again and again, say ______.' })
  await expect(cloze).toBeVisible()
  await page.getByRole('button', { name: '단어장', exact: true }).click()
  await page.getByRole('button', { name: '복습', exact: true }).click()
  await expect(cloze).toBeVisible()
  await expect(page.getByText('빈칸 채우기 · 2 / 3')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)

  await page.getByRole('button', { name: '단어장', exact: true }).click()
  await page.getByRole('button', { name: '단어 수정' }).click()
  await page.getByLabel('단어', { exact: true }).fill('LOOK')
  await expect(page.getByRole('button', { name: '변경 저장' })).toBeDisabled()
  await page.getByLabel('단어', { exact: true }).fill('once again')
  await page.getByRole('textbox', { name: '학습 언어', exact: true }).fill('영어 표현')
  await page.getByRole('textbox', { name: '뜻 (선택)', exact: true }).fill('한 번 더')
  await page.getByRole('button', { name: '변경 저장' }).click()
  await expect(page.getByRole('heading', { name: 'once again' })).toBeVisible()
  await expect(page.getByText('지난 뜻 복습: 기억함', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: '단어 삭제', exact: true }).click()
  await page.getByRole('button', { name: '취소', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'once again' })).toBeVisible()
  await page.getByRole('button', { name: '단어 삭제', exact: true }).click()
  await page.getByRole('button', { name: '단어 삭제 확인' }).click()
  await expect(page.getByRole('button', { name: /once again/ })).toHaveCount(0)
  await page.getByRole('button', { name: /look 보다/ }).click()
  await page.getByText('예문 연결', { exact: true }).click()
  await expect(page.getByRole('option', { name: 'Again and again, say again.' })).toBeAttached()
  await page.getByRole('button', { name: '복습', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'look', exact: true })).toBeVisible()
  await expect(page.getByText('뜻 떠올리기 · 1 / 1')).toBeVisible()
})

test('문장에 기존 단어와 새 단어를 연결하고 해석을 비교한다', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/stilla')
  await page.getByRole('button', { name: '첫 단어 담기' }).click()
  await page.getByRole('textbox', { name: '1행 단어' }).fill('find')
  await page.getByRole('button', { name: '1개 담기' }).click()

  await page.getByRole('button', { name: '문장', exact: true }).click()
  await page.getByLabel('문장 원문').fill('I found an old letter.')
  await page.getByLabel('내가 적은 해석').fill('나는 오래된 편지를 찾았다.')
  await page.getByRole('checkbox', { name: 'find', exact: true }).check()
  await page.getByText('단어장에 없는 단어 추가', { exact: true }).click()
  await page.getByRole('textbox', { name: '새 단어', exact: true }).fill('letter')
  await page.getByRole('button', { name: '새 단어 담기' }).click()
  await page.getByRole('button', { name: '문장 저장' }).click()
  await expect(page.getByText('문장을 저장했어요.')).toBeVisible()
  const sentence = page.getByRole('article').filter({ hasText: 'I found an old letter.' })
  await expect(sentence.getByRole('button', { name: 'find' })).toBeVisible()
  await sentence.getByRole('button', { name: 'letter' }).click()
  await expect(page.getByRole('heading', { name: 'letter', exact: true })).toBeVisible()
  await expect(page.getByRole('blockquote').getByText('I found an old letter.')).toBeVisible()

  await page.getByRole('button', { name: '복습', exact: true }).click()
  await page.getByRole('button', { name: '무작위로 공부하기' }).click()
  await expect(page.getByRole('heading', { name: 'I found an old letter.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '나는 오래된 편지를 찾았다.' })).toBeHidden()
  await page.getByRole('textbox', { name: '내 해석' }).fill('나는 예전 편지를 발견했다.')
  await page.getByRole('button', { name: '해석 비교' }).click()
  await expect(page.getByText('겹치는 표현 · 나는, 편지를')).toBeVisible()
  await expect(page.getByRole('heading', { name: '나는 오래된 편지를 찾았다.' })).toBeVisible()
  await page.getByRole('button', { name: '기억함' }).click()
  await expect(page.getByRole('button', { name: '무작위로 공부하기' })).toBeVisible()
})

test('플래시카드 뒤집기와 기억 평가를 저장하고 이어간다', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/stilla')
  await page.getByRole('button', { name: '첫 단어 담기' }).click()
  await page.getByRole('textbox', { name: '1행 단어' }).fill('letter')
  await page.getByRole('textbox', { name: '1행 뜻' }).fill('편지')
  await page.getByRole('textbox', { name: '2행 단어' }).fill('paper')
  await page.getByRole('textbox', { name: '2행 뜻' }).fill('종이')
  await page.getByRole('button', { name: '2개 담기' }).click()

  await page.getByRole('button', { name: '복습', exact: true }).click()
  await page.getByRole('button', { name: '2장 복습하기' }).click()
  await expect(page.getByRole('heading', { name: 'letter' })).toBeVisible()

  const tab = page.getByRole('button', { name: '플래시카드', exact: true })
  await tab.click()
  await page.getByLabel('카드 유형').selectOption('문장 해석')
  await expect(page.getByRole('button', { name: '공부 시작' })).toBeDisabled()
  await page.getByLabel('카드 유형').selectOption('뜻 떠올리기')
  await page.getByRole('button', { name: '2장 공부하기' }).click()
  const front = page.getByRole('button', { name: '카드 뒤집기' })
  const first = (await front.innerText()).includes('letter') ? 'letter' : 'paper'
  const second = first === 'letter' ? 'paper' : 'letter'
  const firstAnswer = first === 'letter' ? '편지' : '종이'
  await expect(front).not.toContainText(firstAnswer)
  await page.keyboard.press('2')
  await expect(page.getByText('1 / 2장')).toBeVisible()
  await front.press('Space')
  await expect(page.getByRole('button', { name: '앞면으로 돌아가기' })).toContainText(firstAnswer)
  await expect(page.getByRole('button', { name: '어려움 6시간 후' })).toBeVisible()
  await page.keyboard.press('2')
  await expect(front).toContainText(second)
  await expect(page.getByText('2 / 2장')).toBeVisible()
  await page.getByRole('button', { name: '복습', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'letter' })).toBeVisible()
  await tab.click()
  await expect(front).toContainText(second)
  await front.click()
  await page.getByRole('button', { name: '쉬움 4일 후' }).click()
  await expect(page.getByText('2장 공부를 마쳤어요.')).toBeVisible()
  await expect(page.getByRole('button', { name: '공부 시작' })).toBeDisabled()
  await page.getByLabel('공부할 범위').selectOption('all')
  await expect(page.getByRole('button', { name: '2장 공부하기' })).toBeEnabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
