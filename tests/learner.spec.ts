test('이식한 보드 페이지 계산은 기록을 누락하지 않는다', () => {
  const notes = Array.from({ length: 1000 }, (_, id) => id)
  const found: number[] = []
  for (let page = 0; page < 84; page++) {
    const result = boardPage(notes, page)
    expect(result.notes.length).toBeLessThanOrEqual(12)
    found.push(...result.notes)
    for (let i = 0; i < result.notes.length; i++) {
      const position = notePosition(i)
      for (const key of ['--x', '--y', '--mobile-x', '--mobile-y']) {
        expect(position[key]).toBeGreaterThanOrEqual(0)
        expect(position[key]).toBeLessThanOrEqual(1)
      }
    }
  }
  expect(found).toEqual(notes)
  expect(boardPage([], 2)).toEqual({ page: 0, pages: 1, notes: [] })
})

test('개발 미리보기에서 실제 기록 화면을 임시 데이터로 체험한다', async ({ page }) => {
  await page.goto('/post-it-learner')
  await page.getByRole('link', { name: '기록 기능 체험하기' }).click()
  await expect(page).toHaveURL('/post-it-learner/try')
  await expect(page.getByText(/새로고침하면 초기화됩니다/)).toBeVisible()
  await page.getByRole('button', { name: '새 학습 주제' }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel('이름').fill('체험 주제')
  await editor.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page).toHaveURL(/\/post-it-learner\/try\/topics\//)
  await page.getByRole('button', { name: '새 포스트잇' }).click()
  await editor.getByLabel('제목').fill('첫 기록')
  await editor.getByLabel('내용').fill('개발 환경에서 남긴 학습 기록')
  await editor.getByRole('button', { name: '저장', exact: true }).click()
  await page.getByRole('button', { name: /첫 기록/ }).click()
  await expect(page.getByText('개발 환경에서 남긴 학습 기록')).toBeVisible()
  await page.getByRole('link', { name: '예시 보드 보기' }).click()
  await page.getByRole('link', { name: '기록 기능 체험하기' }).click()
  await expect(page.getByRole('link', { name: '체험 주제', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText(/아직 학습 주제가 없습니다/)).toBeVisible()
})
