import { expect, test } from '@playwright/test'

test('모든 기어가 잠겨야 합체하고 직접 출격을 승인할 수 있다', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await page.getByRole('navigation', { name: '내 앱' }).getByRole('link', { name: '결심 출격 관제실' }).click()
  await page.getByRole('button', { name: '새 출격 주제' }).click()
  await page.getByLabel('주제 이름').fill('새 운동화')
  for (let i = 0; i < 3; i++) await page.getByLabel('조건 문구').nth(i).fill(`구매 조건 ${i + 1}`)
  await page.getByRole('button', { name: '주제 저장' }).click()
  await page.getByRole('button', { name: '출격 요청' }).click()
  const approve = page.getByRole('button', { name: '최종 출격 승인' })
  await expect(approve).toBeDisabled()
  await page.getByRole('slider', { name: '구매 조건 1' }).press('End')
  await page.getByRole('button', { name: '구매 조건 2 확인' }).click()
  await expect(approve).toBeDisabled()
  const gear = page.getByRole('slider', { name: '구매 조건 3' })
  await gear.evaluate(element => element.scrollIntoView({ block: 'center' }))
  const box = (await gear.boundingBox())!
  await page.mouse.move(box.x + 18, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width - 1, box.y + box.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect(page.getByText('합체 완료 · 출격 준비')).toBeVisible()
  await page.getByRole('button', { name: '구매 조건 3 잠금 해제' }).click()
  await expect(approve).toBeDisabled()
  await page.getByRole('button', { name: '구매 조건 3 확인' }).click()
  await approve.click()
  await expect(page.getByText('출격 승인', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('대기 시간 전에는 기어를 잠글 수 없으며 보류할 수 있다', async ({ page }) => {
  await page.clock.install()
  await page.goto('/resolve-launch')
  await page.getByRole('button', { name: '출격 요청' }).click()
  await expect(page.getByRole('slider')).toHaveCount(2)
  await page.getByRole('button', { name: '10분 대기 시작' }).click()
  await expect(page.getByRole('slider')).toHaveCount(2)
  await page.clock.fastForward(10 * 60 * 1000 + 1000)
  await expect(page.getByRole('slider')).toHaveCount(3)
  await page.getByRole('button', { name: '격납고 복귀' }).click()
  await expect(page.getByText('지금은 출격하지 않기로 했어요.')).toBeVisible()
})

test('데스크톱 콘솔과 모바일 펼침에서 승인 후에도 메카가 남는다', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/resolve-launch')
  const hangar = page.getByRole('region', { name: '격납고' })
  const rail = page.getByRole('complementary', { name: '승인 조작' })
  await expect(rail).toHaveCSS('position', 'sticky')
  expect((await hangar.boundingBox())!.width).toBeGreaterThan(850)
  await page.screenshot({ path: testInfo.outputPath('control-room-desktop.png') })

  await page.setViewportSize({ width: 440, height: 956 })
  await rail.getByRole('button', { name: '승인 목록 접기' }).click()
  await expect(rail.getByRole('button', { name: '출격 요청' })).toBeHidden()
  await rail.getByRole('button', { name: '승인 목록 펼치기' }).click()
  await expect(rail.getByRole('button', { name: '출격 요청' })).toBeVisible()
  await page.clock.install()
  await rail.getByRole('button', { name: '출격 요청' }).click()
  await rail.getByRole('button', { name: '10분 대기 시작' }).click()
  await page.clock.fastForward(601_000)
  const confirmations = rail.getByRole('button', { name: /다\. 확인$/ })
  await expect(confirmations).toHaveCount(3)
  for (let index = 0; index < 3; index++) await confirmations.first().click()
  const phases = page.getByRole('list', { name: '메카 결합 단계' })
  await expect(phases.locator('[data-ready="true"]')).toHaveCount(6)
  await rail.getByRole('button', { name: '최종 출격 승인' }).click()
  await expect(hangar.getByText('출격 승인', { exact: true })).toBeVisible()
  const painting = hangar.locator('canvas')
  await expect.poll(() => painting.evaluate(canvas => {
    const node = canvas as HTMLCanvasElement
    const pixels = node.getContext('2d')!.getImageData(0, 0, node.width, node.height).data
    return pixels.some((value, index) => index % 4 === 3 && value > 200)
  })).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('control-room-mobile.png'), fullPage: true })
})
